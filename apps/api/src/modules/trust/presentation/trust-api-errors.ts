import { applyDecorators } from "@nestjs/common"
import { ApiResponse } from "@nestjs/swagger"

import { ErrorResponseDto } from "../../identity"

const DESCRIPTIONS: Record<number, string> = {
  400: "Requête invalide (VALIDATION_FAILED, INVALID_CURSOR)",
  401: "Non authentifié (UNAUTHENTICATED, TOKEN_EXPIRED, SESSION_REVOKED)",
  403: "Interdit (INSUFFICIENT_PERMISSION, DECISION_PERMISSION_REQUIRED, SELF_REVIEW_FORBIDDEN, CONFLICT_OF_INTEREST)",
  404: "Introuvable ou non visible (VERIFICATION_NOT_FOUND, VERIFICATION_DOCUMENT_NOT_FOUND, PROPERTY_NOT_FOUND, LISTING_NOT_FOUND, USER_NOT_FOUND, REPORT_NOT_FOUND, SIGNAL_NOT_FOUND)",
  409: "Conflit d'état (VERIFICATION_ALREADY_OPEN, VERIFICATION_ALREADY_VERIFIED, INVALID_VERIFICATION_TRANSITION, VERIFICATION_NOT_EDITABLE, DOCUMENTS_NOT_READY, REPORT_ALREADY_OPEN, INVALID_REPORT_TRANSITION, SIGNAL_ALREADY_REVIEWED)",
  422: "Demande refusée (VERIFICATION_TYPE_NOT_SUPPORTED, VERIFICATION_SCOPE_INVALID, CLAIMED_RELATION_INVALID, IDENTITY_VERIFICATION_REQUIRED, ATTESTATION_REQUIRED, DOCUMENT_TYPE_NOT_ACCEPTED, TOO_MANY_DOCUMENTS, DOCUMENTS_INCOMPLETE, REASON_CODE_INVALID, ASSIGNEE_INVALID, REPORT_SELF_FORBIDDEN)",
  429: "Trop de requêtes (TOO_MANY_REQUESTS, REPORT_LIMIT_REACHED, TOO_MANY_PENDING_UPLOADS)",
}

/** Réponses d'erreur Swagger du module Trust. */
export function TrustApiErrors(...statuses: number[]) {
  return applyDecorators(
    ...statuses.map((status) =>
      ApiResponse({
        status,
        description: DESCRIPTIONS[status],
        type: ErrorResponseDto,
      }),
    ),
  )
}
