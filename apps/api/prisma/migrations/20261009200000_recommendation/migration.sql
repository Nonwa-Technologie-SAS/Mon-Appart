-- Recommendation : recommandations rattachées à l'annonce, retours utilisateur,
-- préférences déclarées complétées. Aucune donnée supprimée.

-- Les recommandations existantes (s'il y en avait) ne connaissent que le bien :
-- impossible de deviner l'annonce. On s'arrête plutôt que de les effacer.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM "recommendations") THEN
    RAISE EXCEPTION 'recommendations contient des lignes sans annonce : migration à adapter (aucune donnée supprimée)';
  END IF;
END
$$;

CREATE TYPE "recommendation_context" AS ENUM ('PERSONALIZED', 'SIMILAR');

CREATE TYPE "recommendation_feedback_type" AS ENUM ('DISPLAYED', 'CLICKED', 'INTERESTED', 'NOT_INTERESTED', 'IRRELEVANT', 'WRONG_BUDGET', 'WRONG_LOCATION');

-- L'unicité porte désormais sur l'annonce et le contexte (location ≠ vente).
DROP INDEX "recommendations_user_id_property_id_algorithm_version_key";

ALTER TABLE "recommendations"
  ADD COLUMN "context" "recommendation_context" NOT NULL DEFAULT 'PERSONALIZED',
  ADD COLUMN "listing_id" BIGINT NOT NULL,
  ADD COLUMN "public_id" UUID NOT NULL DEFAULT gen_random_uuid(),
  ADD COLUMN "rank" SMALLINT;

ALTER TABLE "recommendations"
  ADD CONSTRAINT "recommendations_rank_chk" CHECK ("rank" IS NULL OR "rank" >= 1);

CREATE UNIQUE INDEX "recommendations_public_id_key" ON "recommendations"("public_id");
CREATE INDEX "recommendations_listing_id_property_id_idx" ON "recommendations"("listing_id", "property_id");
CREATE UNIQUE INDEX "recommendations_user_id_listing_id_context_algorithm_versio_key" ON "recommendations"("user_id", "listing_id", "context", "algorithm_version");

ALTER TABLE "recommendations" ADD CONSTRAINT "recommendations_listing_id_property_id_fkey" FOREIGN KEY ("listing_id", "property_id") REFERENCES "listings"("id", "property_id") ON DELETE CASCADE ON UPDATE CASCADE;

CREATE TABLE "recommendation_feedback" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "recommendation_id" BIGINT NOT NULL,
    "type" "recommendation_feedback_type" NOT NULL,
    "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "recommendation_feedback_pkey" PRIMARY KEY ("id")
);

CREATE INDEX "recommendation_feedback_type_created_at_idx" ON "recommendation_feedback"("type", "created_at");
CREATE UNIQUE INDEX "recommendation_feedback_recommendation_id_type_key" ON "recommendation_feedback"("recommendation_id", "type");

ALTER TABLE "recommendation_feedback" ADD CONSTRAINT "recommendation_feedback_recommendation_id_fkey" FOREIGN KEY ("recommendation_id") REFERENCES "recommendations"("id") ON DELETE CASCADE ON UPDATE CASCADE;

ALTER TABLE "user_preferences"
  ADD COLUMN "budget_period" "price_period",
  ADD COLUMN "budget_tolerance_pct" SMALLINT,
  ADD COLUMN "latitude" DECIMAL(9,6),
  ADD COLUMN "longitude" DECIMAL(9,6),
  ADD COLUMN "max_surface" DECIMAL(10,2),
  ADD COLUMN "min_surface" DECIMAL(10,2),
  ADD COLUMN "preferred_bathrooms" SMALLINT,
  ADD COLUMN "radius_m" INTEGER;

ALTER TABLE "user_preferences"
  ADD CONSTRAINT "user_preferences_tolerance_chk" CHECK ("budget_tolerance_pct" IS NULL OR "budget_tolerance_pct" BETWEEN 0 AND 30),
  ADD CONSTRAINT "user_preferences_bathrooms_chk" CHECK ("preferred_bathrooms" IS NULL OR "preferred_bathrooms" >= 0),
  ADD CONSTRAINT "user_preferences_surface_chk" CHECK (("min_surface" IS NULL OR "min_surface" >= 0) AND ("max_surface" IS NULL OR "max_surface" >= 0)),
  ADD CONSTRAINT "user_preferences_surface_range_chk" CHECK ("min_surface" IS NULL OR "max_surface" IS NULL OR "min_surface" <= "max_surface"),
  ADD CONSTRAINT "user_preferences_point_chk" CHECK (
    ("latitude" IS NULL) = ("longitude" IS NULL)
    AND ("latitude" IS NULL OR "latitude" BETWEEN -90 AND 90)
    AND ("longitude" IS NULL OR "longitude" BETWEEN -180 AND 180)
  ),
  ADD CONSTRAINT "user_preferences_radius_chk" CHECK (
    "radius_m" IS NULL OR ("radius_m" BETWEEN 1 AND 100000 AND "latitude" IS NOT NULL)
  );
