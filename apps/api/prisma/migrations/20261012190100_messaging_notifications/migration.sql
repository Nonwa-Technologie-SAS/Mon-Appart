-- Messagerie et notifications (2/2). Additive : `inquiries`, `appointments`,
-- `notifications`, `reports` et `media` sont complétées, pas recréées ;
-- aucune donnée supprimée.

CREATE TYPE "notification_category" AS ENUM (
  'MESSAGES', 'VISITS', 'APPOINTMENT_REMINDERS', 'RECOMMENDATIONS', 'PRICE_DROPS',
  'SAVED_SEARCHES', 'LISTING_UPDATES', 'ACCOUNT', 'MARKETING'
);

CREATE TYPE "notification_channel" AS ENUM ('IN_APP', 'EMAIL', 'SMS', 'PUSH', 'WHATSAPP');

CREATE TYPE "delivery_status" AS ENUM ('PENDING', 'SENDING', 'SENT', 'DELIVERED', 'FAILED', 'CANCELLED');

CREATE TYPE "push_platform" AS ENUM ('ANDROID', 'IOS', 'WEB');

CREATE TYPE "conversation_type" AS ENUM ('PROPERTY_INQUIRY', 'VISIT_COORDINATION');

CREATE TYPE "conversation_status" AS ENUM ('OPEN', 'CLOSED');

CREATE TYPE "participant_role" AS ENUM ('REQUESTER', 'LISTING_SIDE');

CREATE TYPE "participant_state" AS ENUM ('ACTIVE', 'LEFT');

CREATE TYPE "message_type" AS ENUM ('TEXT', 'IMAGE', 'DOCUMENT', 'SYSTEM');

-- ---------------------------------------------------------------------------
-- notifications : catégorie de préférence, idempotence, expiration.
-- ---------------------------------------------------------------------------

ALTER TABLE "notifications"
  ADD COLUMN "category" "notification_category" NOT NULL DEFAULT 'ACCOUNT',
  ADD COLUMN "dedup_key" VARCHAR(200),
  ADD COLUMN "expires_at" TIMESTAMPTZ(6);

UPDATE "notifications" SET "category" = CASE "type"
  WHEN 'MESSAGE' THEN 'MESSAGES'::notification_category
  WHEN 'APPOINTMENT' THEN 'VISITS'::notification_category
  WHEN 'PRICE_DROP' THEN 'PRICE_DROPS'::notification_category
  WHEN 'NEW_RECOMMENDATION' THEN 'RECOMMENDATIONS'::notification_category
  WHEN 'NEW_PROPERTY' THEN 'SAVED_SEARCHES'::notification_category
  ELSE 'ACCOUNT'::notification_category
END;

ALTER TABLE "notifications"
  ADD CONSTRAINT "notifications_expiry_chk" CHECK ("expires_at" IS NULL OR "expires_at" > "created_at");

CREATE UNIQUE INDEX "notifications_user_dedup_key" ON "notifications"("user_id", "dedup_key") WHERE (dedup_key IS NOT NULL);

