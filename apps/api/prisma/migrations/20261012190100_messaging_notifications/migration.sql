-- Un message envoyé ne change ni de conversation, ni de rang, ni de type, ni d'auteur.
CREATE FUNCTION "reject_message_identity_change"() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW."conversation_id" <> OLD."conversation_id"
       OR NEW."seq" <> OLD."seq"
       OR NEW."type" <> OLD."type"
       OR NEW."created_at" <> OLD."created_at"
       OR (NEW."author_id" IS DISTINCT FROM OLD."author_id" AND NEW."author_id" IS NOT NULL) THEN
        RAISE EXCEPTION 'messages : champ immuable modifié'
            USING ERRCODE = 'restrict_violation';
    END IF;
    RETURN NEW;
END;
$$;

CREATE TRIGGER "messages_reject_identity_change"
BEFORE UPDATE ON "messages"
FOR EACH ROW EXECUTE FUNCTION "reject_message_identity_change"();

