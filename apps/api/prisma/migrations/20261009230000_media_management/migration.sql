-- Media : sessions d'upload, file de traitement en base, variantes, purge
-- différée. La table `media` existante est complétée, pas recréée ; aucune
-- donnée supprimée. Les octets restent dans le stockage objet.

-- Un document déjà enregistré avec une URL publique ne peut pas devenir privé
-- sans décision humaine : on s'arrête plutôt que d'effacer l'URL.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM "media" WHERE "type" = 'DOCUMENT' AND "url" IS NOT NULL) THEN
    RAISE EXCEPTION 'media contient des documents avec URL publique : migration à adapter (aucune donnée supprimée)';
  END IF;
END
$$;

CREATE TYPE "media_visibility" AS ENUM ('PUBLIC', 'PRIVATE');

CREATE TYPE "media_variant_kind" AS ENUM ('THUMBNAIL', 'CARD', 'GALLERY', 'LARGE', 'PLAYBACK');

-- Nouvelles valeurs : aucune utilisation dans cette migration (même transaction).
ALTER TYPE "media_status" ADD VALUE 'UPLOADED';

ALTER TYPE "storage_provider" ADD VALUE 'LOCAL';

ALTER TABLE "media"
  ADD COLUMN "metadata" JSONB NOT NULL DEFAULT '{}',
  ADD COLUMN "next_attempt_at" TIMESTAMPTZ(6),
  ADD COLUMN "original_filename" VARCHAR(255),
  ADD COLUMN "processing_attempts" SMALLINT NOT NULL DEFAULT 0,
  ADD COLUMN "processing_error" VARCHAR(100),
  ADD COLUMN "purge_after" TIMESTAMPTZ(6),
  ADD COLUMN "purged_at" TIMESTAMPTZ(6),
  ADD COLUMN "ready_at" TIMESTAMPTZ(6),
  ADD COLUMN "upload_expires_at" TIMESTAMPTZ(6),
  ADD COLUMN "uploaded_at" TIMESTAMPTZ(6),
  ADD COLUMN "uploaded_by_id" BIGINT,
  ADD COLUMN "visibility" "media_visibility" NOT NULL DEFAULT 'PUBLIC';

UPDATE "media" SET "visibility" = 'PRIVATE' WHERE "type" = 'DOCUMENT';

ALTER TABLE "media"
  ADD CONSTRAINT "media_document_private_chk" CHECK ("type" <> 'DOCUMENT' OR "visibility" = 'PRIVATE'),
  ADD CONSTRAINT "media_private_no_url_chk" CHECK ("visibility" = 'PUBLIC' OR "url" IS NULL),
  ADD CONSTRAINT "media_processing_attempts_chk" CHECK ("processing_attempts" >= 0),
  ADD CONSTRAINT "media_metadata_object_chk" CHECK (jsonb_typeof("metadata") = 'object'),
  ADD CONSTRAINT "media_purge_chk" CHECK ("purged_at" IS NULL OR "deleted_at" IS NOT NULL);

CREATE TABLE "media_variants" (
    "id" BIGINT GENERATED BY DEFAULT AS IDENTITY,
    "media_id" BIGINT NOT NULL,
    "kind" "media_variant_kind" NOT NULL,
    "storage_provider" "storage_provider" NOT NULL,
    "storage_key" VARCHAR(512) NOT NULL,
    "is_public" BOOLEAN NOT NULL,
    "url" VARCHAR(2048),
    "mime_type" VARCHAR(127) NOT NULL,
    "file_size" BIGINT NOT NULL,
    "width" INTEGER,
    "height" INTEGER,
    "created_at" TIMESTAMPTZ(6) NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT "media_variants_pkey" PRIMARY KEY ("id"),
    CONSTRAINT "media_variants_file_size_chk" CHECK ("file_size" > 0),
    CONSTRAINT "media_variants_dimensions_chk" CHECK (("width" IS NULL OR "width" > 0) AND ("height" IS NULL OR "height" > 0)),
    CONSTRAINT "media_variants_private_no_url_chk" CHECK ("is_public" OR "url" IS NULL)
);

CREATE UNIQUE INDEX "media_variants_media_id_kind_key" ON "media_variants"("media_id", "kind");
CREATE UNIQUE INDEX "media_variants_storage_provider_storage_key_key" ON "media_variants"("storage_provider", "storage_key");

CREATE INDEX "media_uploaded_by_id_status_idx" ON "media"("uploaded_by_id", "status");
CREATE INDEX "media_job_due_idx" ON "media"("next_attempt_at") WHERE (next_attempt_at IS NOT NULL);
CREATE INDEX "media_upload_expiry_idx" ON "media"("upload_expires_at") WHERE (status = 'PENDING_UPLOAD');
CREATE INDEX "media_purge_due_idx" ON "media"("purge_after") WHERE (purge_after IS NOT NULL AND purged_at IS NULL);

ALTER TABLE "media" ADD CONSTRAINT "media_uploaded_by_id_fkey" FOREIGN KEY ("uploaded_by_id") REFERENCES "users"("id") ON DELETE SET NULL ON UPDATE CASCADE;

ALTER TABLE "media_variants" ADD CONSTRAINT "media_variants_media_id_fkey" FOREIGN KEY ("media_id") REFERENCES "media"("id") ON DELETE CASCADE ON UPDATE CASCADE;
