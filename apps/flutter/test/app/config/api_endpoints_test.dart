import 'package:flutter_test/flutter_test.dart';
import 'package:mon_appart/app/config/api_endpoints.dart';

void main() {
  final endpoints = ApiEndpoints(Uri.parse('http://10.0.2.2:4000'));

  test('health live est hors du préfixe /api/v1', () {
    expect(
      endpoints.healthLive(),
      Uri.parse('http://10.0.2.2:4000/health/live'),
    );
  });

  test('les routes métier passent par /api/v1', () {
    expect(
      endpoints.api('listings'),
      Uri.parse('http://10.0.2.2:4000/api/v1/listings'),
    );
    expect(
      endpoints.api('/search'),
      Uri.parse('http://10.0.2.2:4000/api/v1/search'),
    );
  });

  test('meta correspond au contrat Nest vérifié', () {
    expect(endpoints.meta(), Uri.parse('http://10.0.2.2:4000/api/v1/meta'));
  });

